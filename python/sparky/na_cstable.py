# ----------------------------------------------------------------------------
# Read chemical shift table
def ReadcsTab(cstab):
  iminotab = {}
  cslines = cstab.split('\n')
  cslines = filter(lambda x:x!='', cslines)
  
  for l in cslines:
    triplet,Ncs,Hcs = l.split(',')
    nu = triplet[3]
    atms = imino_groups[nu]
    css = [Ncs, Hcs]
    iminotab[triplet] = {atm:float(cs) for atm,cs in zip(atms, css)}
  
  return iminotab
# ----------------------------------------------------------------------------
# predict based on BP-triplet motif
def PredictImino(triplet, atm):
  
  iminotab =  ReadcsTab(cstab) 
  cs = iminotab[triplet][atm]
  
  return cs
