def na_get_atoms_by_sequence(seq):
  atoms = []
  all_atoms = atomnames.dna_rna_atoms_by_group[seq]
  for atm in all_atoms:
    ast = na_atom_statistics(seq, atm)
    if ast == None: continue  
    atoms.append(atm)
  return atoms
# ----------------------------------------------------------------------------
#
def na_atom_statistics(group_symbol, atom_name):
  ast = na_atom_statistics_table()
  key = (group_symbol, atom_name)
  if ast.has_key(key):
    return ast[key]
  
  return None

