na_atom_stat_table = None
def na_atom_statistics_table():
  
  global na_atom_stat_table
  if na_atom_stat_table == None:
    na_atom_stat_table = {}
    nucleus_translation = { 'H':'1H', 'N':'15N', 'C':'13C', 'P':'31P' }
    for fields in stat_lines:
      gsym = fields[0]
      aname = fields[1]
      nucleus = nucleus_translation[fields[1][0]]
      count = string.atoi(fields[2])
      fmin = string.atof(fields[3])
      fmax = string.atof(fields[4])
      fave = string.atof(fields[5])
      fdev = string.atof(fields[6])
      na_atom_stat_table[(gsym, aname)] = \
        na_atom_stats(gsym, aname, nucleus, count, fmin, fmax, fave, fdev)

  return na_atom_stat_table

